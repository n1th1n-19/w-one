#!/usr/bin/env python3
"""Regenerates the launcher icon vectors from the mascot look picked in the mascot lab.

The noise code mirrors app/src/main/kotlin/app/wone/ui/Mascot.kt and the lab page, including
JavaScript's double-precision hash, so the same numbers give the same outline everywhere.
Usage: tools/gen_mascot.py [frequency amount squareness seed]
"""
import math, sys
from pathlib import Path

FREQ, AMP, SQ, SEED = (float(sys.argv[1]), float(sys.argv[2]), float(sys.argv[3]), int(sys.argv[4])) if len(sys.argv) == 5 else (4.3, 0.17, 5.8, 29)
BODY, FACE = "#E6C9A8", "#2A1A0A"


def i32(x):
    x &= 0xFFFFFFFF
    return x - (1 << 32) if x & 0x80000000 else x


def hash_(ix, iy, seed):
    h = i32(ix * 374761393 + iy * 668265263 + seed * 1442695041)
    h = i32(h ^ ((h & 0xFFFFFFFF) >> 13))
    h = i32(int(float(h) * 1274126177.0))
    h = i32(h ^ ((h & 0xFFFFFFFF) >> 16))
    return ((h & 0xFFFFFFFF) / 4294967295) * 2 - 1


def fade(t): return t * t * t * (t * (t * 6 - 15) + 10)


def noise(x, y, seed):
    x0, y0 = math.floor(x), math.floor(y)
    fx, fy = fade(x - x0), fade(y - y0)
    a, b = hash_(x0, y0, seed), hash_(x0 + 1, y0, seed)
    c, d = hash_(x0, y0 + 1, seed), hash_(x0 + 1, y0 + 1, seed)
    top = a + (b - a) * fx
    return top + ((c + (d - c) * fx) - top) * fy


def field(x, y, seed): return noise(x, y, seed) * 0.75 + noise(x * 2.1 + 5.3, y * 2.1 - 1.7, seed + 11) * 0.25


def outline(R=31, N=360):
    out = []
    for i in range(N):
        t = i / N * math.pi * 2
        c, s = math.cos(t), math.sin(t)
        base = R / ((abs(c) ** SQ + abs(s) ** SQ) ** (1 / SQ))
        r = base * (1 + AMP * field(c * FREQ + 20, s * FREQ + 20, SEED))
        out.append((round(54 + r * c, 2), round(54 + r * s, 2)))
    return out


body = "M" + " L".join(f"{x:g},{y:g}" for x, y in outline()) + " Z"
eyes = "M45,43.2a3.8,3.8 0 1,0 0.01,0z"
eyes2 = "M63,43.2a3.8,3.8 0 1,0 0.01,0z"
res = Path(__file__).resolve().parent.parent / "app/src/main/res/drawable"
head = '<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">'
fg = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/gen_mascot.py: frequency {FREQ}, amount {AMP}, squareness {SQ}, seed {SEED}. -->
{head}
    <path android:fillColor="{BODY}" android:pathData="{body}" />
    <path android:fillColor="{FACE}" android:pathData="{eyes}" />
    <path android:fillColor="{FACE}" android:pathData="{eyes2}" />
    <path android:pathData="M42,57L48,66L54,57L60,66L66,57" android:strokeColor="{FACE}" android:strokeWidth="3.4" android:strokeLineCap="round" android:strokeLineJoin="round" />
</vector>
'''
mono = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Single colour version for themed icons: the body with the eyes cut out. -->
{head}
    <path android:fillColor="#000000" android:fillType="evenOdd" android:pathData="{body} {eyes} {eyes2}" />
</vector>
'''
(res / "ic_launcher_foreground.xml").write_text(fg)
(res / "ic_splash.xml").write_text(fg)
(res / "ic_launcher_monochrome.xml").write_text(mono)
print("wrote launcher icon vectors for", FREQ, AMP, SQ, SEED)
